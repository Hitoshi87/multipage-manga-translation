assert.strictEqual(r.text,'Shinjuku và Yuki, Takumi.');assert.strictEqual(r.honorifics,3);
assert.strictEqual(api.replaceNames('Yuki-kun',[],{stripHonorifics:true,allNames:true}).text,'Yuki');
console.log('Global honorific cleanup matches Python fixtures and works without name mappings PASS');
