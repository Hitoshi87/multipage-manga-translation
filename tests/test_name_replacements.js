const fs=require('fs'),vm=require('vm'),assert=require('assert');
const ctx={};vm.createContext(ctx);vm.runInContext(fs.readFileSync('scripts/repair.jsxinc','utf8'),ctx);
const api=ctx.MTARepair,rule=[{from:'Ajisawa',to:'Shinjuku'}];
let r=api.replaceNames('AJISAWA, ajisawa, Ajisawa! Ajisawasaki đAjisawa Ajisawađ',rule);
assert.strictEqual(r.text,'SHINJUKU, shinjuku, Shinjuku! Ajisawasaki đAjisawa Ajisawađ');
assert.strictEqual(r.count,3);assert.deepStrictEqual(Array.from(r.counts),[3]);
r=api.replaceNames('Ajisawa và Shinjuku',[...rule,{from:'Shinjuku',to:'Osaka'}]);
assert.strictEqual(r.text,'Shinjuku và Osaka','replacements must not cascade');
r=api.replaceNames('Ajisawa Takumi\rAjisawa', [{from:'Ajisawa',to:'Osaka'},{from:'Ajisawa Takumi',to:'Shinjuku Ken'}]);
assert.strictEqual(r.text,'Shinjuku Ken\rOsaka','longest complete name wins');
assert.strictEqual(api.replaceNames('AJISAWA\rTAKUMI',[{from:'Ajisawa Takumi',to:'Shinjuku Ken'}]).text,'SHINJUKU KEN');
assert.strictEqual(api.replaceNames('A+B',[{from:'A+B',to:'X$1'}]).text,'X$1');
assert.strictEqual(api.replaceNames('Nguyễn An, nguyễn an!',[{from:'Nguyễn An',to:'Trần Bình'}]).text,'Trần Bình, trần bình!');
assert.strictEqual(api.nameRules([{from:' A ',to:' B '},{from:'',to:''}]).length,1);
assert.throws(()=>api.nameRules([{from:'A',to:'B'},{from:'a',to:'C'}]),/trùng/);
assert.throws(()=>api.nameRules([{from:'A',to:''}]),/cả tên/);
assert.throws(()=>api.nameRules(Array(4).fill({from:'A',to:'B'})),/3 cặp/);
assert.strictEqual(api.replaceNames('nothing',rule).count,0);
console.log('Three literal name rules: case, Unicode boundaries, whitespace, overlap and no cascades PASS');
const clean=[{from:'Ajisawa',to:'Shinjuku',dropAfter:'Takumi'}],opts={stripHonorifics:true};
r=api.replaceNames('Ajisawa Takumi-san, SHINJUKU - KUN, shinjuku-chan! Takumi-san ở San Francisco.',clean,opts);
assert.strictEqual(r.text,'Shinjuku, SHINJUKU, shinjuku! Takumi-san ở San Francisco.');
assert.strictEqual(r.count,3);assert.strictEqual(r.honorifics,3);assert.strictEqual(r.trimmed,1);
r=api.replaceNames('Shinjuku-san Takumi-kun! Shinjuku Takumiya, Shinjuku-santo, Shinjuku sang đây.',clean,opts);
assert.strictEqual(r.text,'Shinjuku! Shinjuku Takumiya, Shinjuku-santo, Shinjuku sang đây.');
assert.strictEqual(r.honorifics,2);assert.strictEqual(r.trimmed,1);
assert.strictEqual(api.replaceNames('Shinjuku Takumi-san',clean).text,'Shinjuku-san','honorific removal must be optional');
assert.strictEqual(api.replaceNames('Shinjuku Takumi-san',[{from:'Shinjuku',to:'Shinjuku',dropAfter:'Takumi'}],opts).text,'Shinjuku');
assert.strictEqual(api.replaceNames('Shinjuku–san Shinjuku - kun Shinjuku\r-sensei Shinjuku-sama Shinjuku-senpai Shinjuku-dono',clean,opts).text,'Shinjuku Shinjuku Shinjuku Shinjuku Shinjuku Shinjuku');
assert.strictEqual(api.replaceNames('Ajisawa-san Shinjuku-kun',[...clean,{from:'Shinjuku',to:'Osaka'}],opts).text,'Shinjuku Osaka');
assert.strictEqual(api.replaceNames('Takumi, Takeshi, San Francisco, san hô, sandbox.',clean,opts).count,0);
assert.strictEqual(api.replaceNames('Shinjuku san lấp, Shinjuku chan canh.',clean,opts).count,0);
assert.strictEqual(api.nameRules(clean)[0].dropAfter,'Takumi');
assert.throws(()=>api.nameRules([{from:'',to:'',dropAfter:'Takumi'}]),/nhập tên/);
console.log('Honorific cleanup and optional tail shortening are scoped to configured names PASS');
for(const example of JSON.parse(fs.readFileSync('tests/fixtures/honorific_cases.json','utf8'))){
  const clean=api.stripAllHonorifics(example.in);assert.strictEqual(clean.text,example.out);assert.strictEqual(clean.count,example.count);
}
